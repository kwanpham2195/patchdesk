import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { themes } from "@pierre/theming/themes";

const outputPath = resolve(
  process.cwd(),
  "src/renderer/src/pierre-theme-catalog.generated.ts",
);
const generated = renderCatalog();

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      "Pierre theme catalog is stale. Run node scripts/generate-pierre-theme-catalog.mjs.",
    );
  }
  console.log("Pierre theme catalog matches the installed registry.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath}`);
}

function renderCatalog() {
  const light = optionsFor("light");
  const dark = optionsFor("dark");
  return `// Generated by scripts/generate-pierre-theme-catalog.mjs. Do not edit.\n\nexport type PierreThemeOption = {\n  readonly id: string;\n  readonly label: string;\n};\n\nexport const PIERRE_LIGHT_THEMES = ${JSON.stringify(light, null, 2)} as const satisfies ReadonlyArray<PierreThemeOption>;\n\nexport const PIERRE_DARK_THEMES = ${JSON.stringify(dark, null, 2)} as const satisfies ReadonlyArray<PierreThemeOption>;\n`;
}

function optionsFor(colorScheme) {
  return themes.getThemes({ colorScheme }).map((theme) => ({
    id: theme.name,
    label: theme.displayName ?? theme.name.replaceAll("-", " "),
  }));
}
